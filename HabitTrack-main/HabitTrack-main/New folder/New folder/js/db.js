/**
 * db.js - Local-First Storage Engine
 * High-performance relational data manager with IndexedDB/LocalStorage backing.
 * Implements the 4-table schema:
 * 1. Tasks_Master
 * 2. Daily_Logs
 * 3. Day_Overrides
 * 4. Expenses
 */

import { INITIAL_TASKS_MASTER, INITIAL_DAY_OVERRIDES, INITIAL_EXPENSES, generateSeedDailyLogs } from './seedData.js';

const STORAGE_KEYS = {
  TASKS_MASTER: 'habit_tracker_tasks_master',
  DAILY_LOGS: 'habit_tracker_daily_logs',
  DAY_OVERRIDES: 'habit_tracker_day_overrides',
  EXPENSES: 'habit_tracker_expenses',
  LAST_SYNC: 'habit_tracker_last_sync'
};

class LocalDatabase {
  constructor() {
    this.tasksMaster = [];
    this.dailyLogs = [];
    this.dayOverrides = [];
    this.expenses = [];
    this.listeners = new Set();
    this.isInitialized = false;
  }

  async init() {
    if (this.isInitialized) return;

    try {
      const storedTasks = localStorage.getItem(STORAGE_KEYS.TASKS_MASTER);
      const storedLogs = localStorage.getItem(STORAGE_KEYS.DAILY_LOGS);
      const storedOverrides = localStorage.getItem(STORAGE_KEYS.DAY_OVERRIDES);
      const storedExpenses = localStorage.getItem(STORAGE_KEYS.EXPENSES);

      if (storedTasks && storedLogs) {
        this.tasksMaster = JSON.parse(storedTasks);
        this.dailyLogs = JSON.parse(storedLogs);
        this.dayOverrides = storedOverrides ? JSON.parse(storedOverrides) : [];
        this.expenses = storedExpenses ? JSON.parse(storedExpenses) : [];
      } else {
        // Seed initial data
        this.tasksMaster = [...INITIAL_TASKS_MASTER];
        this.dayOverrides = [...INITIAL_DAY_OVERRIDES];
        this.expenses = [...INITIAL_EXPENSES];
        this.dailyLogs = generateSeedDailyLogs();
        this._saveAll();
      }

      // Ensure today's logs exist
      const todayStr = this.getTodayDateString();
      this.ensureLogsForDate(todayStr);

      this.isInitialized = true;
      this.notify();
    } catch (err) {
      console.error('Failed to initialize local database:', err);
      // Fallback in-memory
      this.tasksMaster = [...INITIAL_TASKS_MASTER];
      this.dayOverrides = [...INITIAL_DAY_OVERRIDES];
      this.expenses = [...INITIAL_EXPENSES];
      this.dailyLogs = generateSeedDailyLogs();
      this.isInitialized = true;
    }
  }

  _saveAll() {
    try {
      localStorage.setItem(STORAGE_KEYS.TASKS_MASTER, JSON.stringify(this.tasksMaster));
      localStorage.setItem(STORAGE_KEYS.DAILY_LOGS, JSON.stringify(this.dailyLogs));
      localStorage.setItem(STORAGE_KEYS.DAY_OVERRIDES, JSON.stringify(this.dayOverrides));
      localStorage.setItem(STORAGE_KEYS.EXPENSES, JSON.stringify(this.expenses));
      localStorage.setItem(STORAGE_KEYS.LAST_SYNC, new Date().toISOString());
    } catch (e) {
      console.warn('LocalStorage save failed:', e);
    }
  }

  subscribe(listener) {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  notify(event = {}) {
    this._saveAll();
    for (const listener of this.listeners) {
      try {
        listener(event);
      } catch (e) {
        console.error('Error in db subscriber:', e);
      }
    }
  }

  getTodayDateString() {
    const now = new Date();
    // Default to the user's current date or 2026-11-03
    const year = now.getFullYear();
    const month = String(now.getMonth() + 1).padStart(2, '0');
    const day = String(now.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  /**
   * Automatically generate recurring daily tasks for a date if not already generated.
   * Checks Day_Overrides to apply Rest Day / Holiday logic automatically.
   */
  ensureLogsForDate(dateStr) {
    const existing = this.dailyLogs.filter(l => l.date === dateStr);
    if (existing.length > 0) return existing;

    const override = this.getDayOverride(dateStr);
    const isRestOrHoliday = override && (override.dayType === 'Rest Day' || override.dayType === 'Holiday');

    const newLogs = this.tasksMaster.map(task => {
      return {
        logId: `LOG_${dateStr.replace(/-/g, '')}_${task.taskId}`,
        date: dateStr,
        taskId: task.taskId,
        taskName: task.taskName,
        status: isRestOrHoliday ? 'Skipped' : 'Pending',
        completionTimestamp: null,
        isAdhoc: false,
        linkedExpenseId: null,
        notes: isRestOrHoliday ? `${override.dayType} - Protected Streak` : ''
      };
    });

    this.dailyLogs.push(...newLogs);
    this.notify({ type: 'LOGS_AUTOGENERATED', date: dateStr });
    return this.dailyLogs.filter(l => l.date === dateStr);
  }

  getDailyLogs(dateStr) {
    this.ensureLogsForDate(dateStr);
    return this.dailyLogs.filter(l => l.date === dateStr);
  }

  getLogById(logId) {
    return this.dailyLogs.find(l => l.logId === logId);
  }

  toggleTaskStatus(logId) {
    const log = this.getLogById(logId);
    if (!log) return null;

    let previousStatus = log.status;
    let nextStatus = 'Completed';
    let completionTimestamp = new Date().toISOString();

    if (log.status === 'Completed') {
      nextStatus = 'Pending';
      completionTimestamp = null;
    } else if (log.status === 'Pending') {
      nextStatus = 'Completed';
      completionTimestamp = new Date().toISOString();
    } else if (log.status === 'Skipped') {
      nextStatus = 'Completed';
      completionTimestamp = new Date().toISOString();
    }

    log.status = nextStatus;
    log.completionTimestamp = completionTimestamp;

    this.notify({
      type: 'TASK_TOGGLED',
      logId,
      taskId: log.taskId,
      status: nextStatus,
      previousStatus
    });

    return log;
  }

  setTaskStatus(logId, status, notes = null) {
    const log = this.getLogById(logId);
    if (!log) return;

    log.status = status;
    if (status === 'Completed' && !log.completionTimestamp) {
      log.completionTimestamp = new Date().toISOString();
    } else if (status === 'Pending') {
      log.completionTimestamp = null;
    }
    if (notes !== null) {
      log.notes = notes;
    }

    this.notify({ type: 'TASK_STATUS_UPDATED', logId, status });
    return log;
  }

  /**
   * Add a single-day ad-hoc task without touching Tasks_Master
   */
  addAdHocTask(dateStr, taskName, notes = '') {
    const cleanName = taskName.trim();
    if (!cleanName) return null;

    const logId = `LOG_${dateStr.replace(/-/g, '')}_ADHOC_${Date.now()}`;
    const newLog = {
      logId,
      date: dateStr,
      taskId: `ADHOC_${Date.now()}`,
      taskName: cleanName,
      status: 'Pending',
      completionTimestamp: null,
      isAdhoc: true,
      linkedExpenseId: null,
      notes: notes.trim()
    };

    this.dailyLogs.push(newLog);
    this.notify({ type: 'ADHOC_TASK_ADDED', log: newLog });
    return newLog;
  }

  deleteDailyLog(logId) {
    const index = this.dailyLogs.findIndex(l => l.logId === logId);
    if (index !== -1) {
      const removed = this.dailyLogs.splice(index, 1)[0];
      this.notify({ type: 'LOG_DELETED', log: removed });
      return true;
    }
    return false;
  }

  // --- Day Overrides ---
  getDayOverride(dateStr) {
    return this.dayOverrides.find(o => o.date === dateStr) || {
      date: dateStr,
      dayType: 'Normal',
      reason: ''
    };
  }

  setDayOverride(dateStr, dayType, reason = '') {
    const existingIndex = this.dayOverrides.findIndex(o => o.date === dateStr);
    const override = {
      date: dateStr,
      dayType: dayType, // 'Normal', 'Rest Day', 'Holiday', 'Free Day'
      reason: reason.trim()
    };

    if (existingIndex !== -1) {
      if (dayType === 'Normal') {
        this.dayOverrides.splice(existingIndex, 1);
      } else {
        this.dayOverrides[existingIndex] = override;
      }
    } else if (dayType !== 'Normal') {
      this.dayOverrides.push(override);
    }

    // If marked Rest Day or Holiday, update today's pending recurring tasks to Skipped
    if (dayType === 'Rest Day' || dayType === 'Holiday') {
      const logs = this.dailyLogs.filter(l => l.date === dateStr && !l.isAdhoc);
      logs.forEach(log => {
        if (log.status === 'Pending') {
          log.status = 'Skipped';
          log.notes = `${dayType} - Protected Streak`;
        }
      });
    }

    this.notify({ type: 'DAY_OVERRIDE_CHANGED', date: dateStr, dayType });
    return override;
  }

  // --- Master Tasks ---
  getTasksMaster() {
    return [...this.tasksMaster];
  }

  getTaskMasterById(taskId) {
    return this.tasksMaster.find(t => t.taskId === taskId);
  }

  addTaskMaster({ taskName, targetFrequency = 'Daily', linkedExpenseCategory = '', color = '#10B981', icon = '⭐' }) {
    const taskId = `TASK_${String(this.tasksMaster.length + 1).padStart(3, '0')}_${Date.now().toString().slice(-4)}`;
    const task = {
      taskId,
      taskName: taskName.trim(),
      targetFrequency,
      linkedExpenseCategory: linkedExpenseCategory.trim(),
      createdDate: this.getTodayDateString(),
      icon,
      color
    };

    this.tasksMaster.push(task);

    // Also inject into today's log if not already there
    const todayStr = this.getTodayDateString();
    const existingToday = this.dailyLogs.find(l => l.date === todayStr && l.taskId === taskId);
    if (!existingToday) {
      this.dailyLogs.push({
        logId: `LOG_${todayStr.replace(/-/g, '')}_${taskId}`,
        date: todayStr,
        taskId: taskId,
        taskName: task.taskName,
        status: 'Pending',
        completionTimestamp: null,
        isAdhoc: false,
        linkedExpenseId: null,
        notes: ''
      });
    }

    this.notify({ type: 'TASK_MASTER_ADDED', task });
    return task;
  }

  updateTaskMaster(taskId, updates) {
    const task = this.getTaskMasterById(taskId);
    if (!task) return null;

    Object.assign(task, updates);

    // Update ongoing pending logs with new name
    if (updates.taskName) {
      this.dailyLogs.forEach(l => {
        if (l.taskId === taskId && l.status === 'Pending') {
          l.taskName = updates.taskName;
        }
      });
    }

    this.notify({ type: 'TASK_MASTER_UPDATED', task });
    return task;
  }

  deleteTaskMaster(taskId) {
    const idx = this.tasksMaster.findIndex(t => t.taskId === taskId);
    if (idx !== -1) {
      this.tasksMaster.splice(idx, 1);
      this.notify({ type: 'TASK_MASTER_DELETED', taskId });
      return true;
    }
    return false;
  }

  // --- Expenses ---
  getExpenses() {
    return [...this.expenses].sort((a, b) => new Date(b.date + 'T' + (b.timestamp?.split('T')[1] || '00:00:00')) - new Date(a.date + 'T' + (a.timestamp?.split('T')[1] || '00:00:00')));
  }

  addExpense({ date, amount, category, description, linkedTaskId = null }) {
    const expenseId = `EXP_${date.replace(/-/g, '')}_${Date.now().toString().slice(-4)}`;
    const newExpense = {
      expenseId,
      date,
      amount: parseFloat(amount) || 0,
      category: category || 'General',
      description: (description || '').trim(),
      linkedTaskId: linkedTaskId || null,
      timestamp: new Date().toISOString()
    };

    this.expenses.push(newExpense);

    // If linked to a task, update the corresponding daily log
    if (linkedTaskId) {
      const log = this.dailyLogs.find(l => l.date === date && l.taskId === linkedTaskId);
      if (log) {
        log.linkedExpenseId = expenseId;
      }
    }

    this.notify({ type: 'EXPENSE_ADDED', expense: newExpense });
    return newExpense;
  }

  deleteExpense(expenseId) {
    const idx = this.expenses.findIndex(e => e.expenseId === expenseId);
    if (idx !== -1) {
      const removed = this.expenses.splice(idx, 1)[0];
      // Unlink from any daily log
      this.dailyLogs.forEach(l => {
        if (l.linkedExpenseId === expenseId) {
          l.linkedExpenseId = null;
        }
      });
      this.notify({ type: 'EXPENSE_DELETED', expense: removed });
      return true;
    }
    return false;
  }

  // --- Streak & Calculation Engine (Accounts for Rest Day & Holiday Preservation) ---
  calculateStreaks() {
    // Unique sorted dates
    const dates = Array.from(new Set(this.dailyLogs.map(l => l.date))).sort();
    if (dates.length === 0) return { currentStreak: 0, bestStreak: 0, completionRate: 0 };

    let currentStreak = 0;
    let bestStreak = 0;
    let tempStreak = 0;

    const todayStr = this.getTodayDateString();

    dates.forEach(dStr => {
      const override = this.getDayOverride(dStr);
      const isRestOrHoliday = override.dayType === 'Rest Day' || override.dayType === 'Holiday' || override.dayType === 'Free Day';
      const logs = this.dailyLogs.filter(l => l.date === dStr);

      const regularHabits = logs.filter(l => !l.isAdhoc);
      const completedCount = regularHabits.filter(l => l.status === 'Completed').length;
      const skippedCount = regularHabits.filter(l => l.status === 'Skipped').length;
      const totalCount = regularHabits.length;

      // Successful day condition:
      // 1. If it was a marked Rest Day / Holiday, it explicitly maintains streak
      // 2. Or if all non-skipped regular habits are completed (at least 1 completed or rest day)
      let daySuccess = false;

      if (isRestOrHoliday) {
        daySuccess = true;
      } else if (totalCount > 0 && (completedCount + skippedCount === totalCount) && completedCount > 0) {
        daySuccess = true;
      } else if (dStr === todayStr && completedCount > 0) {
        // Today is in progress; if user completed habits today, treat as streak continuation
        daySuccess = true;
      }

      if (daySuccess) {
        tempStreak++;
        if (tempStreak > bestStreak) {
          bestStreak = tempStreak;
        }
      } else {
        // Break streak only if it's before today
        if (dStr < todayStr) {
          tempStreak = 0;
        }
      }
    });

    currentStreak = tempStreak;

    // Overall completion stats
    const totalLogs = this.dailyLogs.filter(l => !l.isAdhoc);
    const totalCompleted = totalLogs.filter(l => l.status === 'Completed').length;
    const completionRate = totalLogs.length > 0 ? Math.round((totalCompleted / totalLogs.length) * 100) : 0;

    return {
      currentStreak,
      bestStreak: Math.max(currentStreak, bestStreak),
      completionRate,
      totalCompleted
    };
  }

  // --- Export / Import Bridge ---
  exportAllData() {
    return {
      Tasks_Master: this.tasksMaster,
      Daily_Logs: this.dailyLogs,
      Day_Overrides: this.dayOverrides,
      Expenses: this.expenses,
      exportTimestamp: new Date().toISOString()
    };
  }

  importAllData(payload) {
    if (!payload || typeof payload !== 'object') {
      throw new Error('Invalid backup payload');
    }

    if (Array.isArray(payload.Tasks_Master)) {
      this.tasksMaster = payload.Tasks_Master;
    }
    if (Array.isArray(payload.Daily_Logs)) {
      this.dailyLogs = payload.Daily_Logs;
    }
    if (Array.isArray(payload.Day_Overrides)) {
      this.dayOverrides = payload.Day_Overrides;
    }
    if (Array.isArray(payload.Expenses)) {
      this.expenses = payload.Expenses;
    }

    this._saveAll();
    this.notify({ type: 'DATABASE_RESTORED' });
  }
}

export const db = new LocalDatabase();

